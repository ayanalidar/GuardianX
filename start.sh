# GuardianX one-command startup script for Windows (Git Bash)
# Starts: web app (3000) + sentinel engine (3003) + vuln target (3007)
# Auto-creates .env.local if missing (so scans actually work)
# Usage: bash start.sh  OR  double-click GuardianX-Desktop.bat

set -e

# ── Auto-detect project directory ──────────────────────────────────────────
# Works whether run from /d/GuardianX or from a cloned path
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$SCRIPT_DIR"

LOG_DIR="$PROJECT_DIR/logs"
mkdir -p "$LOG_DIR"

