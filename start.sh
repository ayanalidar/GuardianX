  echo "   ✓ .env.local created with Supabase + SMTP credentials"
  echo ""
else
  echo "[0/4] .env.local exists ✓"
fi

# Kill any existing processes on our ports
echo "[1/4] Cleaning up old processes..."
pkill -f "next dev" 2>/dev/null || true
pkill -f "bun.*index.ts" 2>/dev/null || true
sleep 2

# Start sentinel engine (with env vars loaded)
echo "[2/4] Starting Sentinel Engine (port 3003)..."
cd "$PROJECT_DIR/mini-services/sentinel-engine"
export $(grep -v '^#' "$PROJECT_DIR/.env.local" | grep -v '^$' | xargs -d '\n' 2>/dev/null || grep -v '^#' "$PROJECT_DIR/.env.local" | grep -v '^$' | env_import 2>/dev/null || true)
