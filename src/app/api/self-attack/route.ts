// ── Existing scan logic — INTENTIONALLY has gaps ─────────────────────────
// This represents GuardianX's *current* detection capability. The adversarial
// AI's job is to find vulns that AREN'T caught here and write new rules.
const EXISTING_DETECTIONS: ExistingDetection[] = [
  { name: "eval()", pattern: /\beval\s*\(/, severity: "critical", cwe: "CWE-95" },
  { name: "innerHTML assignment", pattern: /\.innerHTML\s*=/, severity: "high", cwe: "CWE-79" },
  { name: "document.write", pattern: /document\.write\s*\(/, severity: "high", cwe: "CWE-79" },
  { name: "SQL string concat", pattern: /(?:SELECT|INSERT|UPDATE|DELETE)\b[^;]*\+\s*\w/i, severity: "critical", cwe: "CWE-89" },
  { name: "child_process.exec", pattern: /(?:child_process|require\(['"]child_process['"]\))[\s\S]*?\.exec\s*\(/, severity: "critical", cwe: "CWE-78" },
  { name: "MD5 hash", pattern: /createHash\(['"]md5['"]\)/, severity: "medium", cwe: "CWE-327" },
  { name: "Hardcoded password", pattern: /\bpassword\s*[:=]\s*['"][^'"]+['"]/, severity: "high", cwe: "CWE-798" },
  { name: "Insecure HTTP", pattern: /fetch\(\s*['"]http:\/\//, severity: "medium", cwe: "CWE-319" },
  { name: "Path traversal fs.readFile", pattern: /fs\.read\w*\s*\(\s*req\./, severity: "high", cwe: "CWE-22" },
  { name: "Python pickle.loads", pattern: /pickle\.loads\s*\(/, severity: "critical", cwe: "CWE-502" },
  { name: "Python eval()", pattern: /\beval\s*\(\s*req\./, severity: "critical", cwe: "CWE-95" },
  { name: "setTimeout string", pattern: /setTimeout\s*\(\s*['"][^'"]+['"]/, severity: "high", cwe: "CWE-95" },
];

function scanWithExistingLogic(code: string): ScanHit[] {
  const hits: ScanHit[] = [];
  for (const det of EXISTING_DETECTIONS) {
    const m = det.pattern.exec(code);
    if (m) {
      const start = Math.max(0, (m.index ?? 0) - 20);
      const end = Math.min(code.length, (m.index ?? 0) + 80);
      hits.push({
        ruleName: det.name,
        severity: det.severity,
        cwe: det.cwe,
        snippet: code.slice(start, end).replace(/\s+/g, " ").trim(),
      });
    }
  }
  return hits;
}

// ── JSON extraction (mirrors src/lib/sentinel/engine/ai.ts) ────────────────
function extractJson(raw: string): string {
  let s = raw.trim();
  const fence = s.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fence) s = fence[1].trim();
  const first = s.search(/[[{]/);
  const lastBrace = s.lastIndexOf("}");
  const lastBracket = s.lastIndexOf("]");
  const last = Math.max(lastBrace, lastBracket);
  if (first !== -1 && last !== -1 && last > first) {
    s = s.slice(first, last + 1);
  }
  return s.trim();
}

// ── Heuristic rule derivation (fallback when LLM is unavailable) ──────────
// Derives a regex from the vuln pattern by extracting the most
// security-relevant token from the code snippet.
function heuristicRuleForVuln(v: VulnPattern): {
  name: string;
  description: string;
  pattern: string;
  severity: Severity;
  cwe: string;
  language: string;
} {
  let pattern = "";
  switch (v.id) {
    case "ssrf-fetch-url":
      pattern = String.raw`fetch\s*\(\s*(?:req|request|input|user|payload)\.`;
      break;
    case "path-traversal-join":
      pattern = String.raw`path\.join\s*\([\s\S]*?req\.`;
      break;
    case "cmd-injection-spawn-shell":
      pattern = String.raw`spawn\s*\([^)]*shell\s*:\s*true`;
      break;
    case "insecure-deserialize":
      pattern = String.raw`serialize\.unserialize\s*\(`;
      break;
    case "prototype-pollution-merge":
      pattern = String.raw`function\s+merge\s*\(\s*\w+\s*,\s*\w+\s*\)[\s\S]*?for\s*\(\s*(?:const|let|var)?\s*\w+\s+in\b`;
      break;
    case "redos-user-regex":
      pattern = String.raw`new\s+RegExp\s*\(`;
      break;
    case "open-redirect":
      pattern = String.raw`res\.redirect\s*\(\s*req\.`;
      break;
    case "jwt-none-alg":
      pattern = String.raw`algorithms\s*:\s*\[[^\]]*['"]none['"]`;
      break;
    case "timing-attack-compare":
      pattern = String.raw`(?:token|secret|password|key|hash)\w*\s*===\s*(?:token|secret|password|key|stored)`;
      break;
    case "hardcoded-api-key":
      pattern = String.raw`['"]sk_(?:live|test)_\w{20,}['"]`;
      break;
    case "weak-rng":
      pattern = String.raw`Math\.random\s*\(\s*\)[\s\S]{0,80}(?:token|secret|password|key|nonce|otp)`;
      break;
    case "xxe-libxml":
      pattern = String.raw`libxmljs\.parseXml\s*\(`;
      break;
    default: {
      // Generic: take the most distinctive function call from the code.
      const fnMatch = v.code.match(/(\w+(?:\.\w+)*)\s*\(/);
      const fn = fnMatch?.[1] ?? "vulnerable";
      pattern = String.raw`${fn}\s*\(`;
    }
  }
  return {
    name: `Auto: ${v.name}`,
    description: `Heuristic rule auto-generated for ${v.name} (${v.cwe}). ${v.expectedDetection}.`,
    pattern,
    severity: v.severity,
    cwe: v.cwe,
    language: v.language,
  };
}

// ── LLM-backed rule generation ────────────────────────────────────────────
async function llmGenerateRule(v: VulnPattern): Promise<{
  name: string;
  description: string;
  pattern: string;
  severity: Severity;
  cwe: string;
  language: string;
} | null> {
  const system = [
    "You are GuardianX's Adversarial AI — a self-attacking red team whose job is to find blind spots in GuardianX's own detection.",
    "You will be given a vulnerable code snippet that the existing scanner MISSED.",
    "Your job: produce a regex-based detection rule that would catch this class of vulnerability in future scans.",
    "Return STRICT JSON only — no prose, no markdown fences.",
  ].join(" ");

  const user = [
    `Vulnerability: ${v.name}`,
    `CWE: ${v.cwe}`,
    `Severity: ${v.severity}`,
    `Language: ${v.language}`,
    `Code:`,
    "```" + v.language,
    v.code,
    "```",
    "",
    "Write a regex pattern that would match this kind of vulnerable code (escape backslashes for JSON).",
    "Return JSON in this EXACT shape:",
    '{"name":"<short name>","description":"<1-2 sentences>","pattern":"<regex string>","severity":"critical|high|medium|low","cwe":"<CWE-NNN>","language":"<lang>"}',
    "Rules:",
    "- The regex MUST be a valid JavaScript regex pattern (the part between /.../), without surrounding slashes or flags.",
    "- The regex MUST match the dangerous construct, not just the literal snippet — generalize to catch variants.",
    "- No markdown fences. No prose. Just JSON.",
  ].join("\n");

  const result = await chatWithFallback({
    system,
    messages: [{ role: "user", content: user }],
    fallback: () => "", // empty = caller falls back to heuristic
    temperature: 0.4,
    maxTokens: 600,
  });

  if (!result.content || result.content.trim() === "") return null;

  let parsed: {
    name?: string;
    description?: string;
    pattern?: string;
    severity?: string;
    cwe?: string;
    language?: string;
  } = {};
  try {
    parsed = JSON.parse(extractJson(result.content)) as typeof parsed;
  } catch {
    return null;
  }

  if (!parsed.pattern || !parsed.name) return null;

  // Validate that the regex actually compiles + matches the snippet.
  let compiled: RegExp;
  try {
    compiled = new RegExp(parsed.pattern);
  } catch {
    return null;
  }
  if (!compiled.test(v.code)) return null;

  const sev = (["critical", "high", "medium", "low"].includes(parsed.severity ?? "")
    ? parsed.severity
    : v.severity) as Severity;

  return {
    name: String(parsed.name).slice(0, 120),
    description: String(parsed.description ?? "").slice(0, 600),
    pattern: String(parsed.pattern),
    severity: sev,
    cwe: parsed.cwe ?? v.cwe,
    language: parsed.language ?? v.language,
  };
}

// ── Route handler ──────────────────────────────────────────────────────────
export async function POST(req: Request) {
  const auth = requireAuth(req);
  if (!auth.ok) return auth.response;

  try {
    // Pick a rotating subset of 5-10 vulns from the library. The rotation
    // changes every hour so re-runs surface different blind spots over time.
    const hourBucket = Math.floor(Date.now() / (1000 * 60 * 60));
    const targetCount = 7 + (hourBucket % 4); // 7..10 snippets
    const rotated = [...VULN_LIBRARY];
    // Deterministic rotation: shift by hourBucket so the order changes.
    const shift = hourBucket % rotated.length;
    const subset = [
      ...rotated.slice(shift),
      ...rotated.slice(0, shift),
    ].slice(0, Math.min(targetCount, VULN_LIBRARY.length));

    const runRows: SelfAttackResult["runs"] = [];
    const rulesAdded: RuleAdded[] = [];
    let missedCount = 0;

    for (const vuln of subset) {
      const hits = scanWithExistingLogic(vuln.code);
      // A "miss" = no existing detection fired on this snippet (or the
      // detection's CWE didn't match the vuln's CWE — i.e. wrong-class hit).
      const matchedByCwe = hits.some((h) => h.cwe === vuln.cwe);
      const detected = hits.length > 0 && matchedByCwe;
      if (!detected) missedCount++;

      runRows.push({
        vulnId: vuln.id,
        vulnName: vuln.name,
        severity: vuln.severity,
        cwe: vuln.cwe,
        language: vuln.language,
        detected,
        matchedRule: detected ? hits[0]?.ruleName : undefined,
        snippet: vuln.code.split("\n")[0]?.slice(0, 80) ?? "",
      });

      // For misses, generate + persist a new detection rule.
      if (!detected) {
        // First check if we already have a rule for this vuln (idempotent
        // — don't double-add). Match by name suffix or CWE+language.
        const existing = await db.detectionRule.findFirst({
          where: {
            OR: [
              { name: { contains: vuln.name } },
              { cwe: vuln.cwe, language: vuln.language },
            ],
          },
        });
        if (existing) {
          // Already have a rule for this blind spot; skip (don't duplicate).
          continue;
        }

        // Try LLM, fall back to heuristic.
        let rule = await llmGenerateRule(vuln).catch(() => null);
        if (!rule) {
          rule = heuristicRuleForVuln(vuln);
        }

        const saved = await db.detectionRule.create({
          data: {
            name: rule.name,
            description: rule.description,
            pattern: rule.pattern,
            severity: rule.severity,
            cwe: rule.cwe,
            language: rule.language,
            autoGenerated: true,
            createdBy: auth.user.email,
            isActive: true,
            hitsCount: 0,
          },
        });
        rulesAdded.push({
          id: saved.id,
          name: saved.name,
          severity: saved.severity as Severity,
          cwe: saved.cwe,
          language: saved.language,
        });
      }
    }

    const testedCount = subset.length;
    const missRate = testedCount > 0 ? Math.round((missedCount / testedCount) * 100) : 0;

    const report = [
      `Adversarial self-attack completed at ${new Date().toISOString()}.`,
      `Tested ${testedCount} synthetic vulnerable snippets against GuardianX's existing scan logic.`,
      `${missedCount} of ${testedCount} (${missRate}%) were NOT detected — these represent blind spots.`,
      `Auto-wrote ${rulesAdded.length} new detection rule(s) to the DetectionRule table.`,
      rulesAdded.length > 0
        ? `New rules: ${rulesAdded.map((r) => `${r.name} (${r.severity}, ${r.cwe ?? "n/a"})`).join("; ")}`
        : `No new rules added (all blind spots already had rules).`,
    ].join(" ");

    // Audit-log the run so /api/self-attack/runs can render history.
    try {
      await db.auditLog.create({
        data: {
          action: "self-attack.run",
          entity: "DetectionRule",
          actor: auth.user.email,
          details: JSON.stringify({
            testedCount,
            missedCount,
            missRate,
            rulesAddedCount: rulesAdded.length,
            rulesAdded: rulesAdded.map(({ id, name, severity, cwe, language }) => ({
              id, name, severity, cwe, language,
            })),
            runRows,
            report,
            generatedAt: new Date().toISOString(),
          }),
        },
      });
    } catch (auditErr) {
      // Audit log failure is non-fatal — the run still succeeded.
      console.warn("[self-attack] audit-log write failed:", auditErr instanceof Error ? auditErr.message : auditErr);
    }

    const result: SelfAttackResult = {
      testedCount,
      missedCount,
      rulesAdded,
      report,
      runs: runRows,
      generatedAt: new Date().toISOString(),
    };
    return NextResponse.json(result);
  } catch (err) {
    console.error("[self-attack] error:", err);
    return NextResponse.json(
      { error: "Self-attack failed. " + (err instanceof Error ? err.message : "Unknown error.") },
      { status: 500 },
    );
  }
}

// GET — convenience for clients that want to fetch the latest run summary
// without walking the runs history. Returns the same shape as POST.
export async function GET(req: Request) {
  const auth = requireAuth(req);
  if (!auth.ok) return auth.response;

  try {
    const last = await db.auditLog.findFirst({
      where: { action: "self-attack.run" },
      orderBy: { createdAt: "desc" },
    });
    if (!last || !last.details) {
      return NextResponse.json({
        testedCount: 0,
        missedCount: 0,
        rulesAdded: [],
        report: "No self-attack runs yet. Click RUN SELF-ATTACK to begin.",
        runs: [],
        generatedAt: new Date().toISOString(),
      });
    }
    try {
      const parsed = JSON.parse(last.details) as SelfAttackResult;
      return NextResponse.json(parsed);
    } catch {
      return NextResponse.json({
        testedCount: 0,
        missedCount: 0,
        rulesAdded: [],
        report: "Last run log was corrupt.",
        runs: [],
        generatedAt: last.createdAt.toISOString(),
      });
    }
  } catch (err) {
    console.error("[self-attack GET] error:", err);
    return NextResponse.json(
      { error: "Failed to load last run." + (err instanceof Error ? err.message : "") },
      { status: 500 },
    );
  }
}
