// ── Types ────────────────────────────────────────────────────────────────
type Severity = "critical" | "high" | "medium" | "low";

interface VulnPattern {
  id: string;
  name: string;
  cwe: string;
  severity: Severity;
  language: string;
  code: string;
  expectedDetection: string; // what a "good" scanner should flag
}

interface ExistingDetection {
  name: string;
  pattern: RegExp;
  severity: Severity;
  cwe: string;
}

interface ScanHit {
  ruleName: string;
  severity: Severity;
  cwe: string;
  snippet: string;
}

interface RuleAdded {
  id: string;
  name: string;
  severity: Severity;
  cwe: string | null;
  language: string;
}

interface SelfAttackResult {
  testedCount: number;
  missedCount: number;
  rulesAdded: RuleAdded[];
  report: string;
  runs: Array<{
    vulnId: string;
    vulnName: string;
    severity: Severity;
    cwe: string;
    language: string;
    detected: boolean;
    matchedRule?: string;
    snippet: string;
  }>;
  generatedAt: string;
}

