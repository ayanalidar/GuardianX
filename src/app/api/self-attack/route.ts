// POST /api/self-attack
//
// Adversarial AI Self-Attack — an AI agent whose job is to find blind spots
// in GuardianX's own detection. It generates synthetic vulnerable code
// snippets that *should* be flagged, runs them through the existing scan
// logic (regex-based), and if GuardianX misses any, the AI auto-writes a
// new detection rule + saves it to the DetectionRule table.
//
// Flow:
//   1. Pick a deterministic-but-rotating subset of 5-10 snippets from the
//      hardcoded 24-pattern vuln library (SQLi, XSS, SSRF, path traversal,
//      command injection, deserialization, hardcoded secrets, weak crypto,
//      prototype pollution, ReDoS, XXE, open redirect, timing attacks, JWT
//      'none' alg, etc.).
//   2. For each snippet, run the EXISTING scan logic (a small set of regex
//      patterns that intentionally has gaps). If the snippet wasn't flagged
//      → it's a false negative (a miss).
//   3. For each miss, ask the LLM (via chatWithFallback) to write a new
//      detection rule: name, description, regex pattern, severity, CWE.
//      On LLM failure, derive a heuristic regex from the vuln pattern.
//   4. Save each new rule to db.detectionRule with autoGenerated=true.
//   5. Audit-log the run (action="self-attack.run") so /api/self-attack/runs
//      can render history.
//   6. Return { testedCount, missedCount, rulesAdded, report }.
//
// Auth-required (Bearer JWT). Dark red theme on the client.

