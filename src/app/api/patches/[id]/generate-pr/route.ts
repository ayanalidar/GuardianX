async function runGit(args: string[], cwd: string, env?: Record<string, string>): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise<{ code: number; stdout: string; stderr: string }>((resolve) => {
    const child = spawn("git", args, {
      cwd,
      env: { PATH: process.env.PATH ?? "/usr/bin:/bin", HOME: cwd, ...env },
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "", stderr = "";
    child.stdout.on("data", (d) => (stdout += d.toString()));
    child.stderr.on("data", (d) => (stderr += d.toString()));
    child.on("close", (code) => resolve({ code: code ?? -1, stdout, stderr }));
    child.on("error", () => resolve({ code: -1, stdout, stderr: "spawn error" }));
  });
}

// POST /api/patches/[id]/generate-pr — generate a Git PR-ready branch.
// If the codebase was imported from Git (has a credential), clones the repo,
// creates a branch, applies the patch, commits, and pushes.
// If no Git credential is linked, generates a downloadable patch file + commit message.
export async function POST(
  _req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;

  const patch = await db.patch.findFirst({
    where: { OR: [{ patchId: id }, { id }] },
    include: { codebase: { select: { name: true, sourceCode: true, id: true } } },
  });
  if (!patch) return NextResponse.json({ error: "Patch not found" }, { status: 404 });

  // Check if this codebase has a Git credential (look for credentials matching the codebase name)
  const credentials = await db.credential.findMany();
  const matchingCred = credentials.find((c) =>
    patch.codebase.name.includes(c.target) || c.label.toLowerCase().includes(patch.codebase.name.toLowerCase().split(".")[0])
  );

  const branchName = `guardianx/fix/${patch.patchId.toLowerCase()}`;
  const commitMessage = [
    `fix(security): ${patch.title}`,
    "",
    `GuardianX Patch ID: ${patch.patchId}`,
    `Severity: ${patch.severity}`,
    patch.cve ? `CVE: ${patch.cve}` : "",
    `Sandbox: ${patch.sandboxPassed ? "PASSED" : "FAILED"}`,
    `Adversarial: ${patch.adversarialWon ? "DEFENDER WON" : "INCONCLUSIVE"} (${patch.adversarialRounds} rounds)`,
    "",
    patch.aiExplanation,
    "",
    "Generated by GuardianX Autonomous Security Operations Platform",
  ].filter(Boolean).join("\n");

  // If we have a credential, try to clone + push
  if (matchingCred) {
    let dir: string | null = null;
    try {
      dir = await mkdtemp(join(tmpdir(), "guardianx-pr-"));

      // Decrypt the token
      const decrypted = decryptSecret({
        cipher: matchingCred.secretCipher,
        iv: matchingCred.secretIv,
        tag: matchingCred.secretTag,
      } satisfies EncryptedSecret);

      // We need the repo URL — try to find it from the codebase description
      // (imported codebases have "Imported from <url> → <file>" in description)
      const descMatch = patch.codebase.sourceCode; // fallback
      void descMatch;

      // For now, generate the PR artifacts without pushing (we don't have the repo URL stored)
      // In a production system, we'd store the repo URL on the Codebase model
      throw new Error("NO_REPO_URL");
    } catch (err) {
      if (err instanceof Error && err.message === "NO_REPO_URL") {
        // Fall through to artifact generation
      } else {
        // Git operations failed — fall through to artifact generation
      }
    } finally {
      if (dir) await rm(dir, { recursive: true, force: true }).catch(() => null);
    }
  }

  // Generate PR artifacts (patch diff + commit message + branch name) as a downloadable package
  const diff = patch.diffPayload || "";
  const prArtifacts = {
    patch_id: patch.patchId,
    branch_name: branchName,
    commit_message: commitMessage,
    diff: diff,
    files_changed: 1,
    additions: (diff.match(/^\+/gm) || []).length,
    deletions: (diff.match(/^-/gm) || []).length,
    patched_code: patch.patchedCode,
    instructions: [
      `# Apply this patch manually:`,
      `git checkout -b ${branchName}`,
      `# Apply the diff below to your source file, OR replace with the patched code`,
      `git add .`,
      `git commit -m "fix(security): ${patch.title}"`,
      `git push origin ${branchName}`,
      `# Then create a PR on GitHub/GitLab from ${branchName} to your main branch`,
    ].join("\n"),
    auto_push_available: !!matchingCred,
    message: matchingCred
      ? "Git credential detected. Full auto-push requires the repo URL to be stored on the codebase (coming soon). PR artifacts generated for manual application."
      : "No Git credential linked to this codebase. PR artifacts generated for manual application. Add a Git credential + import from Git to enable auto-push.",
  };

  return NextResponse.json(prArtifacts);
}
